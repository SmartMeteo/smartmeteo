# Small weather icons for the outlook row under the graph.
# Same source, same fit and same threshold as gen_wx_bitmaps.py. A separate header rather than a
# second size inside weather_icons.h on purpose: regenerating these can never move a pixel of the
# approved large set, which a different Pillow version could otherwise do on a rerun.
import os
from PIL import Image
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "main", "weather_icons_small.h")
USED = [(0, "01d"), (41, "01n"), (1, "02d"), (13, "02n"), (3, "03"), (4, "04"),
        (15, "09"), (8, "10d"), (14, "10n"), (25, "11"), (21, "13"), (29, "50")]
SZ = 32                       # 2026-09-14: as tall as the high over the low; at 36 px it outweighed them
BW = (SZ + 7) // 8

def bits(idx):
    g = Image.open(os.path.join(HERE, "wxv2", f"idx{idx:02d}.png")).convert("L").copy()
    g.thumbnail((SZ, SZ), Image.LANCZOS)
    cv = Image.new("L", (SZ, SZ), 255)
    cv.paste(g, ((SZ - g.size[0]) // 2, (SZ - g.size[1]) // 2))
    ink = np.array(cv) < 128
    out = bytearray()
    for y in range(SZ):
        for xb in range(BW):
            b = 0
            for k in range(8):
                x = xb * 8 + k
                if x < SZ and ink[y, x]:
                    b |= 0x80 >> k
            out.append(b)
    return bytes(out)

h = "// Auto-generated by Software/mockups/gen_wx_small.py from weather_v2.png (wxv2/ slices).\n"
h += f"// {SZ} px weather icons for the outlook row: EPaper::drawBitmap(x,y,bmp,WXS_ICON_W,WXS_ICON_H,0).\n"
h += "#pragma once\n#include <stdint.h>\n#include <string.h>\n\n"
h += f"#define WXS_ICON_W {SZ}\n#define WXS_ICON_H {SZ}\n\n"
for idx, code in USED:
    data = bits(idx)
    h += f"static const uint8_t wxs_{code}[{len(data)}] = {{\n"
    for i in range(0, len(data), 13):
        h += "  " + ",".join(f"0x{b:02X}" for b in data[i:i + 13]) + ",\n"
    h += "};\n\n"
h += """// Same mapping as weatherIcon() in weather_icons.h, onto the small set.
static inline const uint8_t* weatherIconSmall(const char* code) {
    if (!code || strlen(code) < 2) return wxs_03;
    int id = (code[0]-'0')*10 + (code[1]-'0');
    char dn = (strlen(code) >= 3) ? code[2] : 'd';
    switch (id) {
        case 1:  return dn=='n' ? wxs_01n : wxs_01d;
        case 2:  return dn=='n' ? wxs_02n : wxs_02d;
        case 3:  return wxs_03;
        case 4:  return wxs_04;
        case 9:  return wxs_09;
        case 10: return dn=='n' ? wxs_10n : wxs_10d;
        case 11: return wxs_11;
        case 13: return wxs_13;
        case 50: return wxs_50;
        default: return wxs_03;
    }
}
"""
open(OUT, "w").write(h)
print("wrote", os.path.normpath(OUT), len(USED), "icons,", SZ * BW, "bytes each")
