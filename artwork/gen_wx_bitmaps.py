import os
from PIL import Image
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
# index -> C identifier (OWM code)
USED=[(0,"01d"),(41,"01n"),(1,"02d"),(13,"02n"),(3,"03"),(4,"04"),
      (15,"09"),(8,"10d"),(14,"10n"),(25,"11"),(21,"13"),(29,"50")]
SZ=54; FIT=52                          # icon canvas; reduced from 66 (too big, crowded min/max)
BW=(SZ+7)//8                            # 8 bytes/row
def bitmap(idx):
    g=Image.open(os.path.join(HERE, "wxv2", f"idx{idx:02d}.png")).convert("L")
    g=g.copy(); g.thumbnail((FIT,FIT),Image.LANCZOS)
    cv=Image.new("L",(SZ,SZ),255)
    cv.paste(g,((SZ-g.size[0])//2,(SZ-g.size[1])//2))
    a=np.array(cv); ink=(a<128)         # bit=1 where black (drawBitmap sets pixel to color)
    out=bytearray()
    for y in range(SZ):
        for xb in range(BW):
            b=0
            for k in range(8):
                x=xb*8+k
                if x<SZ and ink[y,x]: b|=(0x80>>k)
            out.append(b)
    return bytes(out)
def carr(name,data):
    s=f"static const uint8_t {name}[{len(data)}] = {{\n"
    for i in range(0,len(data),12):
        s+="  "+",".join(f"0x{b:02X}" for b in data[i:i+12])+",\n"
    return s+"};\n"
h ="// Auto-generated by gen_wx_bitmaps.py from Software/mockups/weather_v2.png.\n"
h+="// 1-bit weather icons for EPaper::drawBitmap(x,y,bmp,WX_ICON_W,WX_ICON_H,0) (bit=1 -> black).\n"
h+="// Not included anywhere yet; wire into drawMainScreen during the dashboard port.\n"
h+="#pragma once\n#include <stdint.h>\n#include <string.h>\n\n"
h+=f"#define WX_ICON_W {SZ}\n#define WX_ICON_H {SZ}\n\n"
cnames=[]
for idx,code in USED:
    nm=f"wx_{code}"; cnames.append((code,nm)); h+=carr(nm,bitmap(idx))+"\n"
# mapper: OWM icon code string ("01d".."50n") -> bitmap
h+="""// OWM weather[0].icon code ("01d","10n",...) -> 60x60 bitmap. Day/night distinguished
// for clear/few-clouds/rain; the cloudy/rain-heavy/storm/snow/mist codes share one glyph.
static inline const uint8_t* weatherIcon(const char* code) {
    if (!code || strlen(code) < 2) return wx_03;
    int id = (code[0]-'0')*10 + (code[1]-'0');
    char dn = (strlen(code) >= 3) ? code[2] : 'd';
    switch (id) {
        case 1:  return dn=='n' ? wx_01n : wx_01d;
        case 2:  return dn=='n' ? wx_02n : wx_02d;
        case 3:  return wx_03;
        case 4:  return wx_04;
        case 9:  return wx_09;
        case 10: return dn=='n' ? wx_10n : wx_10d;
        case 11: return wx_11;
        case 13: return wx_13;
        case 50: return wx_50;
        default: return wx_03;
    }
}
"""
open(os.path.join(HERE, "..", "firmware", "main", "weather_icons.h"), "w").write(h)
print("wrote weather_icons.h,",len(USED),"icons, bytes/icon",SZ*BW)
