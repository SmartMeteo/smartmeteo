#pragma once
// Что тест задаёт прибору и что он с прибора считывает.
//
// Всё здесь — ВХОДЫ расписания и его наблюдаемые следствия. Логика между ними — настоящий
// bench_screens.cpp, и ни одна его строка для этой оснастки не менялась: часы перехвачены
// определением time()/gettimeofday() в host.cpp, то есть тем же приёмом, что -Dprivate=public в
// tools/screenhost.
//
// Правило, которое стоит держать в голове при добавлении полей: если значение можно узнать на
// приборе — оно вход и живёт здесь; если оно ВЫВОДИТСЯ прошивкой — оно проверяется, а не задаётся.
#include <stdint.h>
#include <stddef.h>
#include <time.h>
#include <string>
#include <vector>


namespace Host {

// ---- часы -------------------------------------------------------------------------------------
extern time_t  wall;          // что вернёт time(); 0 = часов нет (прибор до первой синхронизации)
extern int64_t mono_us;       // что вернёт esp_timer_get_time()
void   advance(double secs);  // двигает оба: так же, как их двигает настоящее ожидание

// ---- линии ------------------------------------------------------------------------------------
extern bool usb_in;           // кабель вставлен (на плате это НИЗКИЙ уровень на GPIO3)
extern bool button_down;      // кнопка нажата (НИЗКИЙ на GPIO2)

// ---- хаб --------------------------------------------------------------------------------------
// Отвечает ли брокер MQTT. По умолчанию НЕТ — расписание обязано пережить недоступного брокера, и
// это ветка, которую молчаливый успех навсегда спрятал бы. С 2026-10-01 от неё зависит ещё и то,
// пойдёт ли прибор за погодой сам: в режиме хаба погоду приносит хаб, значит «брокер не ответил» —
// это и есть «погоды в этом окне не будет».
extern bool mqtt_ok;

// ---- датчики и питание ------------------------------------------------------------------------
extern bool  bus_ok;          // шина I2C поднялась
extern bool  gauge_ok;        // газомер отвечает
extern float vcell;           // напряжение ячейки, В — регистр VCELL газомера
extern float soc;             // заряд, % — регистр SOC
extern float crate;           // %/ч, со знаком; заряд положителен — регистр CRATE
// Плата v2: газомера нет, ячейка читается делителем на IO4, а STDBY# зарядника — на IO5.
// Напряжение берётся из того же `vcell`: одна ручка на оба пути, и тест, сверяющий их, поймает
// расхождение между арифметикой прошивки и номиналами делителя.
extern bool  sensors_present; // отвечают ли SCD41 и BME690 на пробу — по ним v2 отличается от
                              // v1 с дохлым газомером (battery_source.cpp)
extern bool  adc_cali_ok;     // есть ли калибровка АЦП; без неё прошивка обязана отказаться читать
extern bool  stdby_low;       // STDBY# в нуле = заряд завершён
// Что АЦП делителя подмешивает к честному напряжению. Прошивка обязана пережить каждое из этого,
// и тест ставит их по одному, чтобы видеть, что именно ловит защиту.
extern int   adc_spike_every;   // каждое N-е преобразование — рельс (4095 и 0 по очереди); 0 = нет
extern int   adc_settle_bad;    // столько первых преобразований после настройки канала — ноль
extern int   adc_glitch_bursts; // столько следующих ВСПЫШЕК (сессий АЦП) читают adc_glitch_v
extern float adc_glitch_v;      //   вместо vcell — провал под нагрузкой, а не заряд ячейки
extern float adc_burst_drift_v; // вспышка номер i читает vcell + i * это: ячейка «плывёт»
extern float adc_burst_noise_v; // и ещё ± это по очереди: разброс от радио, без дрейфа среднего
extern int   adc_bursts;        // сколько сессий АЦП открыто с reset() — только чтение
extern float adc_mv_per_code;   // 0: код = милливольты, пересчёт тождественный (так проще читать
                                //   остальные случаи). Иначе настоящий шаг: код = узел / шаг, а
                                //   калибровка отвечает ЦЕЛЫМИ милливольтами, как на приборе
extern int   i2c_probes;      // сколько раз прошивка щупала шину: по нему видно, что ревизия
                              // определяется ОДИН раз за загрузку, а не в каждом опросе статуса
extern int   gauge_reads;     // и сколько раз читала: на плате без газомера тоже НОЛЬ
extern int   gauge_writes;    // сколько раз прошивка писала в газомер: на плате без него должно
                              // быть НОЛЬ, иначе в лог идёт ошибка записи об отсутствующей детали
extern size_t free_heap;      // свободная куча: порог самотеста нового образа

// ---- причина этой загрузки --------------------------------------------------------------------
extern int      reset_reason;      // esp_reset_reason_t
extern int      wake_cause;        // esp_sleep_source_t
extern uint64_t gpio_wake_mask;    // какой вывод разбудил
extern uint8_t  elf_sha[32];       // подменяется, чтобы пройти ветку «образ сменился»

// ---- что прошивка сделала (только чтение из теста) --------------------------------------------
extern uint64_t armed_timer_us;    // последний поставленный таймер; 0 = таймера нет
extern bool     armed_button;      // кнопка вооружена как источник пробуждения
extern uint64_t armed_gpio_mask;   // маска вооружённых выводов
extern int      armed_gpio_level;  // на каком уровне
extern int      sources_cleared;   // сколько раз снимались ВСЕ источники
extern int      restarts;          // сколько раз вызван esp_restart()
extern int      deep_sleeps;       // сколько раз вызван esp_deep_sleep_start()
extern bool     light_sleep_on;    // последнее, что передали esp_pm_configure()
extern int      no_ls_locks;       // сколько блокировок ESP_PM_NO_LIGHT_SLEEP взято и не отдано
extern int      rollbacks;         // esp_ota_mark_app_invalid_rollback_and_reboot()
extern int      marked_valid;      // esp_ota_mark_app_valid_cancel_rollback()
extern int      intr_type[31];     // тип прерывания, выставленный на выводе
extern bool     intr_enabled[31];

// ---- лог --------------------------------------------------------------------------------------
// Часть решений прошивки видна ТОЛЬКО в логе. Захват превращает их в проверки.
extern std::vector<std::string> log_lines;
bool logged(const char *needle);          // есть ли строка с этой подстрокой
int  logged_count(const char *needle);

// ---- сброс между случаями ---------------------------------------------------------------------
// Приводит заглушки к состоянию «новый прибор». Переменные RTC живут в bench_screens.cpp и
// обнуляются самим тестом — он их видит, потому что включает этот файл целиком.
void reset(void);
void clear_settings(void);
void set_u8 (const char *key, uint8_t v);
void set_u32(const char *key, uint32_t v);
void set_float(const char *key, float v);
void set_str(const char *key, const char *v);
bool has_key(const char *key);

}  // namespace Host

// Из сна и перезагрузки прошивка не возвращается. Оснастка выходит из них броском: тест ставит
// прибор в известное состояние, зовёт фазу и ловит то, чем она кончилась. Иначе проверять пришлось
// бы отдельные куски вместо целой фазы — а дефекты 0.9.43 и 0.10.11 были именно в порядке фаз.
struct HostDeepSleep { uint64_t timer_us; bool button_armed; };
struct HostRestart   { int count; };

