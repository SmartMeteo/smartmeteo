#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Экран: то, что увидит стекло, против утверждённого снимка.

Кадр рисует tools/screenhost — это screen.cpp и epaper.cpp прибора, собранные на компьютере, а не
перерисовка на Python. Значит несовпадение с golden означает, что изменился сам прибор.

    tests/t_screen.py            проверить
    tests/t_screen.py --accept   принять текущий вид как правильный (смотреть глазами до того)
"""
import os, subprocess, sys, hashlib

HERE   = os.path.dirname(os.path.abspath(__file__))
HOST   = os.path.join(HERE, "..", "tools", "screenhost")
GOLDEN = os.path.join(HERE, "golden")
STATES = ["normal", "extreme", "band", "bandoffline", "bandnopw", "mmhg",
          "empty", "night", "charge", "offline",
          # Выключение вручную. Эти два экрана держат стекло месяцами без питания и читаются
          # глазами через комнату, поэтому у них своя проверка размера букв ниже.
          "off", "offconfirm", "offlongname",
          # Настраиваемая нижняя полоса. Данные в каждом — худшие, какие бывают: «00:00»/«20:00»
          # (самые широкие часы суток), «100», «-40» (роняет строку до размера 2), и случай, когда
          # нет ни часов, ни погоды — полоса прибора в Ultra Save, который никогда не был в сети.
          "strip_sun", "strip_mixed", "strip_wide", "strip_nodata",
          # Калибровка CO2 на стекле (2026-09-30). Четыре состояния, через которые проходит прогон, а
          # не набор образцов: каждое — настоящее сочетание, которое прошивка выдаёт.
          "calib_settling", "calib_measuring", "calib_done", "calib_stopped",
          # Сырость переехала из вердикта о воздухе в блок влажности (решение владельца,
          # 2026-10-02). Три состояния, а не одно: сама сырость; сырость вместе с духотой — её
          # прежний каскад показать не мог вовсе, «Damp» забирал слово; и сырость вместе со
          # Storm, где два инвертированных блока сливаются в одну полосу и разделитель колонок
          # приходится возвращать белым.
          "damp", "dampstuffy", "dampstorm"]
W, H   = 400, 300

fails = []
def ok(cond, what):
    print(("  ок      " if cond else "  ПРОВАЛ  ") + what)
    if not cond: fails.append(what)

def render(state):
    """PGM из screenhost -> плоский bytes, 1 байт на пиксель (0 чернила, 255 бумага)."""
    out = os.path.join(HOST, "out_%s.pgm" % state)
    subprocess.run([os.path.join(HOST, "screenhost"), state], cwd=HOST, check=True,
                   stdout=subprocess.DEVNULL)
    with open(out, "rb") as f:
        data = f.read()
    # P5\n400 300\n255\n
    head = 0
    for _ in range(3):
        head = data.index(b"\n", head) + 1
    px = data[head:]
    assert len(px) == W * H, "%s: %d пикселей вместо %d" % (state, len(px), W * H)
    return px

def to_pbm(px):
    """1 бит на пиксель — golden в 15 КБ вместо 120 КБ, и его по-прежнему можно открыть глазами."""
    rows = []
    for y in range(H):
        row = bytearray((W + 7) // 8)
        for x in range(W):
            if px[y * W + x] == 0:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return b"P4\n%d %d\n" % (W, H) + b"".join(rows)

def row_h(px, y0, y1, x0, x1, value):
    """Высота строки: от верхней до нижней строки пикселей цвета `value` в этой области.

    Мерить самый длинный вертикальный штрих нельзя — он зависит от того, какие буквы попались:
    у «Q» хвост, у «!» разрыв под восклицанием, и у одного и того же кегля выходят разные числа.
    Высота строки от кегля зависит, а от набора букв — нет."""
    rows = [y for y in range(y0, y1)
            if any(px[y * W + x] == value for x in range(x0, x1))]
    return (max(rows) - min(rows) + 1) if rows else 0

def main():
    accept = "--accept" in sys.argv
    # ВСЕГДА пересобирать. Раньше здесь стояло "если двоичника нет", и это делало весь набор
    # бессмысленным ровно тогда, когда он нужен: правишь screen.cpp, запускаешь тест, он рендерит
    # ПРОШЛЫЙ двоичник и радостно сообщает, что снимки совпали. Поймано 2026-09-21 намеренным
    # сломом — уменьшил слово OFF вдвое, и проверка прошла. Сборка занимает секунды; ложная зелень
    # в единственном тесте, который сторожит стекло, стоит дороже.
    subprocess.run([os.path.join(HOST, "build.sh")], check=True, stdout=subprocess.DEVNULL)
    os.makedirs(GOLDEN, exist_ok=True)

    print("== экран: снимок ==")
    for st in STATES:
        px  = render(st)
        pbm = to_pbm(px)
        g   = os.path.join(GOLDEN, st + ".pbm")
        if accept or not os.path.exists(g):
            # Говорим, что РЕАЛЬНО поменялось. Раньше --accept печатал одинаковое «принят» для всех
            # десяти состояний, и по выводу нельзя было понять, какие из них сдвинулись, — то есть
            # правило «принимать, посмотрев глазами» проверить было нечем. Снимок, уехавший заодно
            # с чужой правкой, проскочил бы молча.
            was = open(g, "rb").read() if os.path.exists(g) else None
            with open(g, "wb") as f: f.write(pbm)
            if was is None:
                print("  НОВЫЙ   %s (%s)" % (st, hashlib.sha256(pbm).hexdigest()[:12]))
            elif was != pbm:
                print("  ИЗМЕНЁН %s (%s) — посмотрите на него" % (st, hashlib.sha256(pbm).hexdigest()[:12]))
            else:
                print("  без изменений  %s" % st)
            continue
        with open(g, "rb") as f: want = f.read()
        if pbm == want:
            ok(True, "%s совпадает со снимком" % st)
        else:
            # Где именно разошлось — чтобы не гадать по картинке.
            wp = want[want.index(b"\n", want.index(b"\n") + 1) + 1:]
            gp = pbm [pbm .index(b"\n", pbm .index(b"\n") + 1) + 1:]
            diff = [(y, x) for y in range(H) for x in range(W)
                    if ((gp[y*50 + x//8] >> (7 - x % 8)) & 1) != ((wp[y*50 + x//8] >> (7 - x % 8)) & 1)]
            box = (min(x for _, x in diff), min(y for y, _ in diff),
                   max(x for _, x in diff), max(y for y, _ in diff))
            ok(False, "%s: %d пикселей разошлись, область x %d..%d, y %d..%d"
                      % (st, len(diff), box[0], box[2], box[1], box[3]))

    print("== экран: инварианты ==")
    for st in STATES:
        px = render(st)
        ink = sum(1 for v in px if v == 0) / float(W * H)
        ok(0.005 < ink < 0.70, "%s: чернил %.1f%% — кадр не пустой и не залит" % (st, ink * 100))

    # Пароль на плашке — та самая правка: со стекла его читают глазами, значит буквы должны быть
    # кратно крупнее адреса. Плашка инвертирована, поэтому меряется белый штрих, а не чёрный.
    # Экран «выключен» существует ровно затем, чтобы его прочитали. Если слово OFF усохнет до
    # размера подписи, он перестанет отличаться от зависшего прибора — а это весь его смысл.
    px = render("off")
    word = row_h(px, 90, 170, 0, 400, 0)
    ok(word >= 40, "слово OFF высотой %d px — читается через комнату" % word)
    ink_rows = [y for y in range(H) if any(px[y*W + x] == 0 for x in range(W))]
    # Порог 6, а не 20: логотип встал под самый верх по раскладке, и это поле, а не край.
    # Проверка здесь про то, что панель не режет картинку, а не про вкус к отступам.
    ok(ink_rows and min(ink_rows) >= 6 and max(ink_rows) < 292,
       "экран «выключен»: ничего не упирается в край (y %d..%d)" % (min(ink_rows), max(ink_rows)))
    cols = [x for x in range(W) if any(px[y*W + x] == 0 for y in range(H))]
    ok(cols and min(cols) > 10 and max(cols) < 390,
       "экран «выключен»: ничего не уходит за правый край (x %d..%d)" % (min(cols), max(cols)))
    # Логотип: он и есть верхняя треть экрана, и если генератор отдаст пустую картинку, снимок
    # это заметит, а доля чернил — нет. Меряем отдельно.
    logo = sum(1 for y in range(10, 130) for x in range(W) if px[y*W + x] == 0)
    ok(logo > 1500, "логотип нарисован (%d пикселей чернил в его полосе)" % logo)
    # Имя прибора пишет владелец, длина у него любая. Слишком длинное должно исчезать целиком,
    # а не вылезать за край: предложение — содержание, имя — любезность, уступает любезность.
    pxl = render("offlongname")
    cl = [x for x in range(W) if any(pxl[y*W + x] == 0 for y in range(H))]
    ok(cl and min(cl) > 10 and max(cl) < 390,
       "длинное имя не выталкивает строку за край (x %d..%d)" % (min(cl), max(cl)))

    px = render("band")
    # Окно измерения НАХОДИТ плашку, а не помнит её координаты, и столбцы берутся внутри неё.
    # Обе поправки — из одного дня (2026-09-30), и обе потому, что проверка опиралась на соседей:
    #   * столбцы шли от нуля и мерили белое поле СЛЕВА от плашки; проходило лишь потому, что
    #     внешняя рамка обрывала тот столбец. Рамку убрали — «высота адреса» скакнула 7 -> 12 px;
    #   * строки были записаны числами 263..275; плашка съехала на пиксель вниз, дойдя до края
    #     панели, и в окно попала строка белой страницы над ней — 7 -> 10 px.
    # Проверку, которую держит посторонняя линия или запомненная координата, ломает любая правка
    # рядом, и каждый раз это выглядит как дефект там, где его нет.
    # Край панели проверяем ПЕРВЫМ и отдельно от строк: это самое дешёвое утверждение, оно не
    # зависит от поиска плашки, и при отступе именно оно называет причину, а не молчит за спиной
    # обвалившегося измерения.
    ok(px[298*W + 0] == 0 and px[299*W + 0] == 0,
       "band: плашка доходит до левого нижнего угла панели")
    ok(px[299*W + 249] == 0, "band: и до нижнего края по всей своей ширине")
    # Плашка ищется от своей НИЖНЕЙ чернильной строки, а не от низа панели. Разница выходит боком
    # ровно при том дефекте, который здесь и стерегут: отступ снизу оставляет строку 299 белой,
    # поиск «первая бумага снизу» отвечает сразу же, и окно измерения уезжает за панель — набор
    # падает обвалом вместо внятного провала (поймано намеренным сломом 2026-09-30).
    col = [y for y in range(H - 1, H - 60, -1) if px[y * W + 4] == 0]
    ok(bool(col), "band: в колонке плашки есть чернила")
    if col:
        band_bot = col[0]
        band_top = next((y for y in range(band_bot, H - 60, -1) if px[y * W + 4] != 0), H - 61) + 1
        ok(band_top < H - 20, "band: плашка найдена (верх на y=%d, низ %d)" % (band_top, band_bot))
        # Внутри плашки: 2 px поля, адрес кеглем 1, зазор, затем пароль кеглем 3 до самого низа.
        split = band_top + 12
        addr = row_h(px, band_top, split, 4, 246, 255)
        pwd  = row_h(px, split, band_bot + 1, 4, 246, 255)
        ok(addr > 0 and pwd > 0, "band: обе строки плашки нарисованы (адрес %d px, пароль %d px)" % (addr, pwd))
        # Не равенство, а «не меньше»: знакоместо glcd — 5x8, и восьмую строку занимают только выносные.
        # В адресе их нет (7 px), в пароле «Q» её занимает (24 px вместо 21). Кегль втрое больше, а
        # сколько строк знакоместа попало в набор — дело случая.
        ok(pwd >= 3 * addr, "band: пароль не ниже трёхкратного адреса (%d против %d px)" % (pwd, addr))

    print("экран            провалов %d" % len(fails))
    return 1 if fails else 0

if __name__ == "__main__":
    sys.exit(main())
