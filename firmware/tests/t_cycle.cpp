// Расписание пробуждений — настоящий main/bench_screens.cpp, собранный на этой машине.
//
// Зачем это есть. bench_screens.cpp — единственный крупный файл прошивки, которого не касался ни
// один тест: сон, радио, шину I2C и панель заменить нечем, кроме прибора. Но РЕШЕНИЕ отделимо от
// исполнения: что прибор собирался измерить, когда собирался выйти в сеть, будет ли кадр полным, на
// какой срок он собирался уснуть — всё это чистая арифметика над настройками, часами и состоянием
// RTC. Её и проверяем; сон по-прежнему проверяется на приборе.
//
// Чего тут НЕТ и не будет: «прибор действительно проснулся», «панель действительно нарисовала»,
// «радио действительно подключилось». Оснастка отвечает на вопрос «что прошивка решила», а не «что
// получилось». Второй вопрос — прогон на железе.
//
// Ни одна строка прошивки для этого не менялась. Тест включает .cpp целиком, потому что Plan, Tick и
// сами функции файловые, а часы перехвачены в host.cpp — тот же приём, что -Dprivate=public в
// tools/screenhost.
//
// Почти каждая проверка ниже привязана к дефекту, который уже случался: даты в комментариях — из
// журнала CLAUDE.md. Проверка, под которой нет такой истории, стоит дешевле.
//
// ОДНО ОГРАНИЧЕНИЕ, названное здесь, чтобы будущая проверка на нём не обманулась. На приборе
// каждое пробуждение — новая загрузка, и функциональные статики начинаются заново. Здесь все случаи
// идут в ОДНОМ процессе, поэтому статика переживает fresh(). В функциях под проверкой такая одна —
// `static bool asked` в plan_tick(), она один раз за загрузку зовёт ClockSync::forceClockSync().
// Значит на приборе её зовёт каждое пробуждение с подозрительными часами, а здесь — только первое.
// Ни одна проверка ниже на неё не опирается, и опираться не должна: это единственное место, где
// оснастка и прибор расходятся по построению, а не по настройке.
