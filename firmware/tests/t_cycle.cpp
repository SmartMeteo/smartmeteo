        fresh(); Host::gauge_ok = false; I2CManager::getInstance().init();
        BatterySource::revision(I2CManager::getInstance().getBusHandle());
        ok(Host::logged("board v2"), "плата v2 названа в логе");

        fresh(); Host::bus_ok = false; I2CManager::getInstance().init();
        BatterySource::revision(I2CManager::getInstance().getBusHandle());
        ok(Host::logged("cannot tell which board"),
           "и молчащая шина тоже названа — «не знаю» должно быть видно, а не выглядеть как v2");
